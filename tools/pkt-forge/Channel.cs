    }

    static string Step(string name, string sequenceTitle, IEnumerable<string> activities, string next)
    {
        _refs.Add(name);
        var sb = new StringBuilder();
        sb.Append($"<FlowStep x:Name=\"{name}\"><Sequence DisplayName=\"{sequenceTitle}\">");
        foreach (string a in activities) sb.Append(a);
        sb.Append("</Sequence>");
        if (next != null) sb.Append("<FlowStep.Next>").Append(next).Append("</FlowStep.Next>");
        sb.Append("</FlowStep>");
        return sb.ToString();
    }

    static string Decision(string name, string title, string condition, string whenTrue, string whenFalse)
    {
        _refs.Add(name);
        var sb = new StringBuilder();
        sb.Append($"<FlowDecision x:Name=\"{name}\" Condition=\"{condition}\" DisplayName=\"{title}\">");
