        sb.Append("</FlowDecision>");
        return sb.ToString();
    }

    static string Member(string name, string type, string description)
    {
        string desc = description == null ? "" : $"<asw:Description2Attribute Description=\"{description}\" />";
        return $"<x:Property Name=\"{name}\" Type=\"{type}\"><x:Property.Attributes><asw:EnabledFlag2Attribute EnabledFlag=\"True\" />{desc}</x:Property.Attributes></x:Property>";
