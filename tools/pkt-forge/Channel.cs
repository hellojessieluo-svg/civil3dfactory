using System.Globalization;
using System.Text;

namespace PktForge;

/// <summary>
/// Channel (dredge / ditch) subassembly parameters: flat bottom -> side slope 1:Slope1H -> optional bench
/// (BenchWidth wide, reached at BenchHeight above the bottom) -> slope 1:Slope2H up to the ground (EG_Surface).
/// When the ground is lower than BenchHeight above the bottom the bench is skipped and the first slope daylights.
/// Optional lining slab under the bottom (LiningThickness > 0 at generation time) adds a closed shape coded "Lining".
/// </summary>
internal sealed record ChannelSpec
{
    public string Name { get; init; } = "Channel";
    public double BottomHalfWidth { get; init; } = 10;
    public double Slope1H { get; init; } = 3;
    public double BenchHeight { get; init; } = 0;
    public double BenchWidth { get; init; } = 2;
    public double Slope2H { get; init; } = 3;
    public double LiningThickness { get; init; } = 0;
    public string Units { get; init; } = "m";
    public string OutDir { get; init; } = ".";
    public string Description { get; init; } =
        "Dredge channel side: flat bottom (BottomHalfWidth) at the profile elevation, side slope 1:Slope1H, " +
        "optional bench (BenchWidth) at BenchHeight above the bottom, then 1:Slope2H up to existing ground (EG_Surface). " +
        "Point codes Origin/Bottom/Toe/Hinge/BenchIn/BenchOut/Daylight plus origin/toe-side/controlpoint-side/mp-side/daylight-side; link codes Top/Datum/Bottom/Slope/Bench/Daylight/Cut plus bottom/slope-side/flat-side. Generated by PktForge.";

    public const string Usage =
        """
        Channel subassembly (flat bottom + side slope + optional bench + optional lining shape):
          PktForge channel [options]
          --name <name>              subassembly name (default Channel); writes <name>_LEFT.pkt / <name>_RIGHT.pkt
          --bottom-half-width <m>    half of the bottom width on this side (default 10)
          --slope1-h <n>             first side slope 1:n (default 3)
          --bench-height <m>         height of the bench above the bottom; 0 = no bench (default 0)
          --bench-width <m>          bench width (default 2)
          --slope2-h <n>             slope above the bench 1:n (default 3)
          --lining <m>               lining slab thickness under the bottom; > 0 adds a closed shape coded Lining (default 0)
          --units / --out / --desc   same as daylight
        """;

    public static ChannelSpec Parse(string[] args)
    {
        var spec = new ChannelSpec();
        for (int i = 1; i < args.Length; i += 2)
        {
            string key = args[i];
            if (i + 1 >= args.Length) throw new ArgumentException(key + " is missing a value");
            string val = args[i + 1];
            spec = key switch
            {
                "--name" => spec with { Name = val },
                "--bottom-half-width" => spec with { BottomHalfWidth = Num(key, val) },
                "--slope1-h" => spec with { Slope1H = Num(key, val) },
                "--bench-height" => spec with { BenchHeight = Num(key, val) },
                "--bench-width" => spec with { BenchWidth = Num(key, val) },
                "--slope2-h" => spec with { Slope2H = Num(key, val) },
                "--lining" => spec with { LiningThickness = Num(key, val) },
                "--units" => spec with { Units = val },
                "--out" => spec with { OutDir = val },
                "--desc" => spec with { Description = val },
                _ => throw new ArgumentException("Unknown option: " + key)
            };
        }
        if (spec.BottomHalfWidth <= 0) throw new ArgumentException("bottom-half-width must be positive");
        if (spec.Slope1H <= 0 || spec.Slope2H <= 0) throw new ArgumentException("slope ratios must be positive");
        if (spec.BenchHeight < 0 || spec.BenchWidth < 0 || spec.LiningThickness < 0) throw new ArgumentException("bench and lining values must not be negative");
        return spec;
    }

    private static double Num(string key, string val)
    {
        if (!double.TryParse(val, NumberStyles.Float, CultureInfo.InvariantCulture, out double d))
            throw new ArgumentException(key + " is not a number: " + val);
        return d;
    }
}

/// <summary>Writes the channel .pkt (atc parameter block + XAML flowchart), reusing the shared package plumbing.</summary>
internal static class ChannelWriter
{
    public static string Write(ChannelSpec spec, bool isLeft)
    {
        string side = isLeft ? "Left" : "Right";
        string toolName = PktWriter.SanitizeIdentifier(spec.Name) + "_" + side;
        string guid = Guid.NewGuid().ToString("N");
        int sideVal = isLeft ? 1 : 0;
        string n(double d) => PktWriter.N(d);

        var ps = new StringBuilder();
        ps.Append($"            <Side DataType=\"long\" TypeInfo=\"16\" DisplayName=\"Side\" Description=\"Side\">{sideVal}<Enum><Left DisplayName=\"Left\">1</Left><Right DisplayName=\"Right\">0</Right></Enum></Side>\n");
        ps.Append($"            <BottomHalfWidth DataType=\"double\" TypeInfo=\"16\" DisplayName=\"BottomHalfWidth\" Description=\"Half of the bottom width on this side\">{n(spec.BottomHalfWidth)}</BottomHalfWidth>\n");
        ps.Append($"            <Slope1H DataType=\"double\" TypeInfo=\"16\" DisplayName=\"Slope1H\" Description=\"First side slope 1:Slope1H (horizontal per 1 vertical)\">{n(spec.Slope1H)}</Slope1H>\n");
        ps.Append($"            <BenchHeight DataType=\"double\" TypeInfo=\"16\" DisplayName=\"BenchHeight\" Description=\"Bench height above the bottom; 0 = no bench\">{n(spec.BenchHeight)}</BenchHeight>\n");
        ps.Append($"            <BenchWidth DataType=\"double\" TypeInfo=\"16\" DisplayName=\"BenchWidth\" Description=\"Bench width\">{n(spec.BenchWidth)}</BenchWidth>\n");
        ps.Append($"            <Slope2H DataType=\"double\" TypeInfo=\"16\" DisplayName=\"Slope2H\" Description=\"Slope above the bench 1:Slope2H\">{n(spec.Slope2H)}</Slope2H>");
        if (spec.LiningThickness > 0)
            ps.Append($"\n            <LiningThickness DataType=\"double\" TypeInfo=\"16\" DisplayName=\"LiningThickness\" Description=\"Lining slab thickness under the bottom\">{n(spec.LiningThickness)}</LiningThickness>");

        string outPath = Path.Combine(spec.OutDir, spec.Name + "_" + side.ToUpperInvariant() + ".pkt");
        PktWriter.WritePackage(outPath, guid,
            ChannelXaml.Build(spec, isLeft),
            PktWriter.BuildAtcXml(toolName, PktWriter.XmlEscape(spec.Description), guid, ps.ToString(), spec.Units));
        return outPath;
    }
}

