/// <summary>
/// Slope-from-top subassembly: the side slope starts where the offset target (TopLine, e.g. an offset alignment or a
/// design line) meets existing ground and runs down at 1:Slope1H to the baseline elevation (the design bottom profile).
/// It ends at the toe and leaves the bottom open: a stock MarkPoint on one toe plus a stock LinkToMarkedPoint on the
/// other closes the channel, so the bottom width follows the two design lines instead of a parameter.
/// Points: origin, mp-side (bottom elevation under the top line), daylight-side / controlpoint-side, toe-side.
/// Links: slope-side (+ Top, Datum, Slope, Cut).
/// </summary>
internal sealed record SlopeTopSpec
{
    public string Name { get; init; } = "SlopeTop";
    public double Slope1H { get; init; } = 3;
    public double MinHalfBottom { get; init; } = 0.5;
    public double PreviewTopOffset { get; init; } = 15;
    public string Units { get; init; } = "m";
    public string OutDir { get; init; } = ".";
    public string Description { get; init; } =
        "Slope from the top line: the side slope starts where the TopLine offset target meets existing ground (EG_Surface) and runs " +
        "down at 1:Slope1H to the baseline (design bottom) elevation, ending at the toe. Close the bottom with MarkPoint + LinkToMarkedPoint. " +
        "Point codes Origin/origin, mp-side, Daylight/daylight-side/controlpoint-side, Toe/Bottom/toe-side; link codes Top/Datum/Slope/Cut/slope-side. Generated by PktForge.";

    public const string Usage =
        """
        Slope-from-top subassembly (top line target -> slope down to the design bottom; bottom closed by LinkToMarkedPoint):
          PktForge slopetop [options]
          --name <name>              subassembly name (default SlopeTop); writes <name>_LEFT.pkt / <name>_RIGHT.pkt
          --slope1-h <n>             side slope 1:n (default 3)
          --min-half-bottom <m>      the toe never comes closer to the baseline than this (default 0.5)
          --preview-offset <m>       offset of the TopLine target in the Subassembly Composer preview (default 15)
          --units / --out / --desc   same as daylight
        """;

    public static SlopeTopSpec Parse(string[] args)
    {
        var spec = new SlopeTopSpec();
        for (int i = 1; i < args.Length; i += 2)
        {
            string key = args[i];
            if (i + 1 >= args.Length) throw new ArgumentException(key + " is missing a value");
            string val = args[i + 1];
            spec = key switch
            {
                "--name" => spec with { Name = val },
                "--slope1-h" => spec with { Slope1H = Num(key, val) },
                "--min-half-bottom" => spec with { MinHalfBottom = Num(key, val) },
                "--preview-offset" => spec with { PreviewTopOffset = Num(key, val) },
                "--units" => spec with { Units = val },
                "--out" => spec with { OutDir = val },
                "--desc" => spec with { Description = val },
                _ => throw new ArgumentException("Unknown option: " + key)
            };
        }
        if (spec.Slope1H <= 0) throw new ArgumentException("slope1-h must be positive");
        if (spec.MinHalfBottom < 0 || spec.PreviewTopOffset <= 0) throw new ArgumentException("min-half-bottom must not be negative and preview-offset must be positive");
        return spec;
    }

    private static double Num(string key, string val)
    {
        if (!double.TryParse(val, NumberStyles.Float, CultureInfo.InvariantCulture, out double d))
            throw new ArgumentException(key + " is not a number: " + val);
        return d;
    }
}

internal static class SlopeTopWriter
{
    public static string Write(SlopeTopSpec spec, bool isLeft)
    {
        string side = isLeft ? "Left" : "Right";
        string toolName = PktWriter.SanitizeIdentifier(spec.Name) + "_" + side;
        string guid = Guid.NewGuid().ToString("N");
        int sideVal = isLeft ? 1 : 0;
        string n(double d) => PktWriter.N(d);

        var ps = new StringBuilder();
        ps.Append($"            <Side DataType=\"long\" TypeInfo=\"16\" DisplayName=\"Side\" Description=\"Side\">{sideVal}<Enum><Left DisplayName=\"Left\">1</Left><Right DisplayName=\"Right\">0</Right></Enum></Side>\n");
        ps.Append($"            <Slope1H DataType=\"double\" TypeInfo=\"16\" DisplayName=\"Slope1H\" Description=\"Side slope 1:Slope1H (horizontal per 1 vertical)\">{n(spec.Slope1H)}</Slope1H>\n");
        ps.Append($"            <MinHalfBottom DataType=\"double\" TypeInfo=\"16\" DisplayName=\"MinHalfBottom\" Description=\"The toe never comes closer to the baseline than this\">{n(spec.MinHalfBottom)}</MinHalfBottom>");

        string outPath = Path.Combine(spec.OutDir, spec.Name + "_" + side.ToUpperInvariant() + ".pkt");
        PktWriter.WritePackage(outPath, guid,
            SlopeTopXaml.Build(spec, isLeft),
            PktWriter.BuildAtcXml(toolName, PktWriter.XmlEscape(spec.Description), guid, ps.ToString(), spec.Units));
        return outPath;
    }
}

