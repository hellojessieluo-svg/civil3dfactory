        if (whenFalse != null) sb.Append("<FlowDecision.False>").Append(whenFalse).Append("</FlowDecision.False>");
        sb.Append("</FlowDecision>");
        return sb.ToString();
    }

    static string Member(string name, string type, string description)
    {
